"""

Performs adaptive GWAS permutation testing on a single SNP-trait combination using GEMMA.

Implements association testing with GEMMA between a single SNP and a trait, and compares this
to a null distribution of association statistics generated by permuting the SNP data. The
null distribution is generated by permuting the SNP data while keeping the kinship matrix
constant. The script will do several rounds of permutation testing, stopping when the
number of association statistics in the null distribution exceeds the association between
the original SNP and trait a number of times (perm_stop). The script will also stop if the
number of permutations exceeds n_perm_max. The script will output the p-value for the
association between the SNP and trait, the number of permutations performed, and the
number of association statistics in the null distribution that exceed the association
between the SNP and trait.

Args:
    gemma_path (str): Path to the GEMMA executable.
    phenotype (str): Path to the phenotype file.
    snpfile (str): Path to the genotype file.
    accessions (str): Path to the accessions file.
    eigenvec (str): Path to the eigenvector file.
    eigenval (str): Path to the eigenvalue file.
    covariates (str): Path to the covariates file (Optional).
    temp_dir (str): Temporary directory for intermediate files.
    snp (str): The SNP to be tested.
    output (str): Path to the output file.
    n_perm (list): List of integers specifying the number of permutations to perform.
    perm_stop (int): Number of times the association statistic must exceed the original
        association statistic for the script to stop prematurely.
        
Outputs:
    A CSV file containing the following columns:
    The original p-value for the association between the SNP and trait,
    the p-value for the association between the SNP and trait after permutation testing,
    the number of permutations performed, 
    and the number of association statistics in the null distribution that exceed the original association statistic.
"""
import os
import argparse
import numpy as np
import csv
import subprocess
import sys
import time

def main():
    argparser = argparse.ArgumentParser(description="Perform adaptive GWAS permutation testing.")
    argparser.add_argument("--gemma_path", required=True, help="Path to the GEMMA executable.")
    argparser.add_argument("--phenotype", required=True, help="Path to the phenotype file.")
    argparser.add_argument("--snpfile", required=True, help="Path to the genotype file.")
    argparser.add_argument("--accessions", required=True, help="Path to the accessions file.")
    argparser.add_argument("--eigenvec", required=True, help="Path to the eigenvector file.")
    argparser.add_argument("--eigenval", required=True, help="Path to the eigenvalue file.")
    argparser.add_argument("--covariates", required=False, default=None, help="Path to the covariates file (Optional).")
    argparser.add_argument("--temp_dir", required=True, help="Temporary directory for intermediate files")
    argparser.add_argument("--snp", required=True, help="SNP to be tested.")
    argparser.add_argument("--output", required=True, help="Path to the output file.")
    argparser.add_argument("--n_perm", type=int, nargs='+', required=True, help="List of integers specifying the number of permutations to perform.")
    argparser.add_argument("--perm_stop", type=int, required=True,
                           help="Number of times the association statistic must exceed the original association statistic for the script to stop prematurely.")
    args = argparser.parse_args()

    accessions = [line.rstrip() for line in open(args.accessions, 'r')] # Lines in the genotype file
    gemma_path = args.gemma_path
    phenotype = args.phenotype
    eigenvec = args.eigenvec
    eigenval = args.eigenval
    temp_dir = args.temp_dir
    snp = args.snp
    output = args.output
    n_perm = change_n_perm(args.n_perm)
    perm_stop = args.perm_stop
    covariates = args.covariates
    
    genotypes = get_genotypes(args.snpfile, snp, accessions)
    
    (original_p_value, perm_p_value, count_perm, exceed_count) = permutation_test(
        gemma_path,
        phenotype,
        genotypes,
        n_perm,
        perm_stop,
        temp_dir,
        eigenvec,
        eigenval,
        covariates
    )
    with open(output, "w") as f:
        f.write(f"{original_p_value},{perm_p_value},{count_perm},{exceed_count}\n")


def write_permutations(genotypes, n_permutations, output_file, batch_size=1000):
    """
    Generate and save permutations of a genotype - SNP - to write it to
    a BIMBAM format file. The output is written to a CSV file in a format
    compatible with BIMBAM.
    
    Args:
    genotypes (list of int): Genotype data for the SNP.
    n_permutations (int): Number of shuffles to generate.
    output_file (str): Path to the output CSV file.
    batch_size (int): Number of rows to write at once for batch processing.
    
    Returns:
    None: Writes the output directly to the specified file.
    """
    genotypes_np = np.array(genotypes)
    rng = np.random.default_rng()
    newline = os.linesep
    header = ['NA', 'NA', 'NA']
    
    with open(output_file, 'w', buffering=100_000_000) as f:
        writer = csv.writer(f, lineterminator=newline)
        for start in range(0, n_permutations, batch_size):
            current_batch_size = min(batch_size, n_permutations - start)
            batch = rng.permuted(np.tile(genotypes_np, (current_batch_size, 1)), axis=1)
            writer.writerows([header + row.tolist() for row in batch])


def permutation_test(gemma_path, phenotype, genotypes, n_perm, perm_stop, temp_dir, eigenvec, eigenval, covariates=None):
    """
    Perform permutation testing for a given SNP-trait combination.
    
    Args:
        gemma_path (str): Path to the GEMMA executable.
        phenotype (str): Path to the phenotype file.
        genotypes (list of int): Genotype data for the SNP.
        n_perm (list of int): List of integers specifying the number of permutations to perform.
        perm_stop (int): Number of times the association statistic must exceed the original
            association statistic for the script to stop prematurely.
        temp_dir (str): Temporary directory for intermediate files.
        eigenvec (str): Path to the eigenvector file.
        eigenval (str): Path to the eigenvalue file.
        covariates (str): Path to the covariates file (Optional).

    Returns:
        tuple: A tuple containing the unpermuted p-value, permutation p-value,
        count of permutations, and number of times the permutation p-values exceeded
        the unpermuted p-value.
    """
    os.makedirs(temp_dir, exist_ok=True)
    original_p_value = get_snp_association_statistic(gemma_path, phenotype, genotypes, temp_dir, eigenvec, eigenval, covariates)
    exceed_count = 0
    count_perm = 0
    
    for perm in n_perm:
        count_perm += perm
        temp_file_prefix = "myPermutationTestFiles" # temporary file prefix for each permutation batch
        start_time = time.time()
        write_permutations(genotypes, perm, os.path.join(temp_dir, f"{temp_file_prefix}.a"))
        elapsed_time = time.time() - start_time
        print(f"Permutation {perm} took {elapsed_time:.2f} seconds", flush = True)
        
        start_time = time.time()
        run_gemma(gemma_path, phenotype, os.path.join(temp_dir, f"{temp_file_prefix}.a"), eigenvec, eigenval, covariates, temp_file_prefix, temp_dir)
        elapsed_time = time.time() - start_time
        print(f"GEMMA took {elapsed_time:.2f} seconds", flush = True)
        p_values = parse_gemma_output(os.path.join(temp_dir, f"{temp_file_prefix}.assoc.txt"))
        exceed_count += np.sum(p_values < original_p_value)
        if exceed_count >= perm_stop:
            break
    
    # Clean up temporary files
    for file in os.listdir(temp_dir):
        os.remove(os.path.join(temp_dir, file))
    os.rmdir(temp_dir)
    
    perm_p_value = (exceed_count + 1) / (count_perm + 1)
    return original_p_value, perm_p_value, count_perm, exceed_count
    
    
def change_n_perm(n_perm, batch_size = 10**7):
    """
    Change the number of permutations to perform based on the input list,
    removing the number of permutations in subsequent rounds that are done previously,
    and changing the number of maximum permutation to perform in any one round,
    to minimize memory usage by GEMMA. That is physical memory on the disk, not RAM.
    The function will return a new list of integers specifying the number of permutations to perform in each round.
    
    Args:
        n_perm (list of int): List of integers specifying the number of permutations to perform.
        batch_size (int): Max number of permutations to perform in a single batch.
        
    Returns:
    n_perm (list of int): Updated list of integers specifying the number of permutations to perform.
    
    Example:
        Input: [10, 100, 1000, 10000], batch_size=800
        Output: [10, 90, 800, 800, ..., 800, 300] (12×800)
    """
    if not n_perm:
        raise ValueError("No permutations specified.")
    
    non_cum = [n_perm[0]]
    for i in range(1, len(n_perm)):
        non_cum.append(n_perm[i] - n_perm[i - 1])
        
    result = []
    carry = 0
    for i in range(len(non_cum)):
        carry += non_cum[i]
        full_chunks = carry // batch_size
        if full_chunks > 0:
            result.extend([batch_size] * full_chunks)
            carry = carry % batch_size
        else:
            result.append(carry)
            carry = 0
    if carry > 0:
        result.append(carry)
    return result
    
    
def run_gemma(gemma_path, phenotype, BIMBAM, eigenvec, eigenval, covariates, outfile, outdir):
    """
    Run GEMMA (Genome-wide Efficient Mixed Model Association) analysis.

    Args:
        phenotype (str): Path to phenotype file.
        BIMBAM (str): Path to BIMBAM-format genotype file.
        eigenvec (str): Path to eigenvectors file.
        eigenval (str): Path to eigenvalues file.
        covariates (str): Path to the covariates file (Optional).
        outfile (str): Base name for output files.
        outdir (str): Output directory path.

    Raises:
        subprocess.CalledProcessError: If GEMMA execution fails.
    """
    cov_str = f"-c {covariates}" if covariates else ""
    command = f"""
    {gemma_path} -g {BIMBAM} -p {phenotype} -n 1 \\
          -lmm 1 -u {eigenvec} -d {eigenval} {cov_str} \\
          -o {outfile} -outdir {outdir}
    """ 
    
    try:
        result = subprocess.run(
            command,
            shell=True,
            check=True,
            capture_output=True,
            text=True,
            executable="/bin/bash"
        )
        return result.stdout  # Return GEMMA's output for potential logging
        
    except subprocess.CalledProcessError as e:
        # Write errors to stderr
        sys.stderr.write(f"\nERROR: GEMMA execution failed (exit code {e.returncode})\n")
        sys.stderr.write(f"Command: {e.cmd}\n")
        sys.stderr.write(f"Stderr:\n{e.stderr}\n")
        # Re-raise to allow caller handling
        raise


def get_genotypes(genotype_file, snp, lines):
    """
    Get the genotypes for a specific SNP from the genotype file.

    Args:
        genotype_file (str): Path to the genotype file.
        snp (str): SNP identifier.
        lines (list of char): list of lines to extract genotypes for.

    Returns:
        list of str: Genotypes for the specified SNP.
    """
    with open(genotype_file, "r") as f:
        header = f.readline().strip().split(",")
        indices = [header.index(line) for line in lines]
        for line in f:
            split_line = line.strip().split(",")
            if split_line[0] == snp:
                return [int(split_line[i]) for i in indices]
    raise ValueError(f"SNP {snp} not found in genotype file.")


def get_snp_association_statistic(gemma_path, phenotype_file, genotype, temp_dir, eigenvec, eigenval, covariates=None):
    """
    Get the pvalue for a specific SNP-trait combination.

    Args:
        gemma_path (str): Path to the GEMMA executable.
        phenotype_file (str): Path to the phenotype file.
        genotype (list of int): Genotype data for the SNP.
        temp_dir (str): Temporary directory for intermediate files.
        eigenvec (str): Path to the eigenvector file.
        eigenval (str): Path to the eigenvalue file.
        covariates (str): Path to the covariates file (Optional).

    Returns:
        float: pvalue for the SNP-trait combination.
    """
    temporary_genotype_file = os.path.join(temp_dir, "temp_genotype.a")
    output_file_name = "realsnp"
    output_file = os.path.join(temp_dir, f"{output_file_name}.assoc.txt")
    with open(temporary_genotype_file, "w") as f:
        f.write("rs1,A,T,") # Dummy values for BIMBAM format
        f.write(",".join(map(str, genotype)))
        f.write("\n")
    run_gemma(gemma_path, phenotype_file, temporary_genotype_file, eigenvec, eigenval, covariates, output_file_name, temp_dir)
    p_value = parse_gemma_output(output_file)[0]
    return p_value


def parse_gemma_output(output_file):
    """
    Parse GEMMA output file to extract p-values.

    Args:
        output_file (str): Path to the GEMMA output file.

    Returns:
        list of float: List containing p-values.
    """
    rows = count_rows_in_file(output_file)
    if rows == 0:
        raise ValueError(f"No data found in GEMMA output file: {output_file}")
    p_values = np.zeros(rows)
    with open(output_file, "r") as f:
        header = f.readline().strip().split()
        index = header.index("p_wald") # Find the index of the p-value column when using the Wald test
        for i, line in enumerate(f):
            p_values[i] = float(line.strip().split()[index])
    return p_values


def count_rows_in_file(file_path):
    """
    Count the number of rows in a file.

    Args:
        file_path (str): Path to the file.

    Returns:
        int: Number of rows in the file.
    """
    with open(file_path, "r") as f:
        # Skip the header line
        next(f)
        return sum(1 for _ in f)


if __name__ == "__main__":
    main()